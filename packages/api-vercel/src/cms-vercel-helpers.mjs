/**
 * cms-vercel helper — installed into the user's app/ as
 * `script/_cmsAdmin.cms`. Routes /api/v1/bo/:bo/save and /delete through
 * bo.persist so writes participate in the runtime's full BO lifecycle
 * (audit log, validators, deleteRule).
 *
 * Plain .mjs (not .ts) so it's importable from both compiled TS and the
 * bin/* CLI scripts at runtime without a build step.
 */

export const HELPER_CMS_PATH = 'script/_cmsAdmin.cms';

export const HELPER_CMS_SOURCE = `// @generated by @casemaster/api-vercel — DO NOT EDIT.
// Routes /api/v1/bo/:bo/save and /delete through bo.persist so writes
// participate in the runtime's BO lifecycle (audit log, validators,
// deleteRule checks). Re-run \`npx cms-admin-install-helper\` to refresh.

function save(boName, data)
    set('//act_err', '')
    set('//act_row', null())

    set('id', _onError(pb.get([data], 'id'), null()))
    if isNotNull([id])
        set('row', bo.quickLoad([boName], [id], group: '*'))
        if isNull([row])
            set('//act_err', concat('row not found: ', [boName], '#', [id]))
            exit-function
        end-if
    else
        set('row', bo.create([boName]))
    end-if

    iterate iterator.ofPB([data])
        if ne([_key], 'id')
            bo.setAttr([row], [_key], [_value])
        end-if
    end-iterate
    bo.persist([row])
    set('//act_row', [row])
end-function

function delete(boName, id)
    set('//act_err', '')
    set('row', bo.quickLoad([boName], [id], group: '*'))
    if isNull([row])
        set('//act_err', concat('row not found: ', [boName], '#', [id]))
        exit-function
    end-if
    bo.delete([row])
end-function
`;
